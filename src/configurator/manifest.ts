function paintCap(names: string[], reason: string) {
  return {
    supported: names.length > 0,
    reason,
    materialNameIncludes: names,
    meshNameIncludes: [],
  };
}

function off(reason: string) {
  return {
    supported: false,
    reason,
    materialNameIncludes: [],
    meshNameIncludes: [],
  };
}

